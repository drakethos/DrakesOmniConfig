#!/usr/bin/env python3
"""Copies Drakes Asset Forge's runtime (Format + Runtime sources) into src/Forge, namespaced into DrakesOmniConfig.

Same transform Asset Forge's own "C# mod project" export uses, so OmniConfig carries its own copy of Forge (looks,
tints, borrowed materials, parts, fields) and players install one mod. Re-run after Forge changes:

  python3 build/scripts/sync_forge.py [path to DrakesAssetForge/Forge]
"""
import os
import shutil
import sys

here = os.path.dirname(os.path.abspath(__file__))
repo = os.path.normpath(os.path.join(here, "..", ".."))
forge = sys.argv[1] if len(sys.argv) > 1 else os.path.normpath(os.path.join(repo, "..", "DrakesWorkshop", "DrakesAssetForge", "Forge"))
out = os.path.join(repo, "src", "Forge")
ns = "DrakesOmniConfig"
# the shared runtime's own plugin class would register a second BepInEx plugin; Testing holds its TestLab hooks
skip_files = {"ForgeRuntimePlugin.cs"}
skip_dirs = {"bin", "obj", "Testing", "thunderstore"}

if os.path.isdir(out):
    shutil.rmtree(out)
count = 0
for part in ("Format", "Runtime"):
    root = os.path.join(forge, part)
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in skip_dirs]
        for name in filenames:
            if not name.endswith(".cs") or name in skip_files:
                continue
            src = os.path.join(dirpath, name)
            rel = os.path.relpath(src, forge)
            code = open(src, encoding="utf-8").read()
            code = code.replace("DrakesForge.Format", ns + ".Forge.Format").replace("namespace DrakesForge.Runtime;", f"namespace {ns}.Forge;")
            dest = os.path.join(out, rel)
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            with open(dest, "w", encoding="utf-8") as f:
                f.write("// <auto-generated>\n// Forge (Drakes Asset Forge) compiled into DrakesOmniConfig by build/scripts/sync_forge.py. Don't edit; re-run the script.\n// </auto-generated>\n#nullable enable\n" + code)
            count += 1
print(f"copied {count} Forge source file(s) into {out}")
